const catalogSlug = (value:string) => value
  .normalize("NFKD")
  .replace(/[ıİ]/g,"i")
  .replace(/[şŞ]/g,"s")
  .replace(/[ğĞ]/g,"g")
  .replace(/[üÜ]/g,"u")
  .replace(/[öÖ]/g,"o")
  .replace(/[çÇ]/g,"c")
  .toLowerCase()
  .replace(/[^a-z0-9]+/g,"-")
  .replace(/(^-|-$)/g,"");

